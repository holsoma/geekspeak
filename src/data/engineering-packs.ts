function t(
  id: string,
  name: string,
  summary: string,
  explanation: string,
  example: string,
  misconception: string,
  source: string,
  prompt: string,
  options: Question["options"],
  answer: number,
  feedback: string,
  aliases: string[] = [],
): Term {
  return {
    id,
    name,
    aliases,
    summary,
    explanation,
    example,
    misconception,
    source,
    question: { prompt, options, answer, explanation: feedback },
  };
}

